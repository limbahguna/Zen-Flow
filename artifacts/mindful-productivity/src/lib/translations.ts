/**
 * Look up a translation key for the given language.
 * Falls back to English, then to the key itself if not found.
 */
export function t(
  lang: LanguageCode,
  key: string,
  values?: Record<string, string | number>,
): string {
  const text = translations[lang]?.[key] ?? translations.en[key] ?? key;
  if (!values) return text;
  return text.replace(/\{(\w+)\}/g, (match, name: string) =>
    values[name] === undefined ? match : String(values[name]),
  );
}

/** Exposes the active dictionary key set for parity regression tests. */
export function getTranslationKeys(lang: LanguageCode): string[] {
  return Object.keys(translations[lang] ?? {});
}
