/**
 * Static translation dictionary — all strings are hardcoded, never AI-generated.
 * Lookup: t(lang, key) → string, falling back to English if key/lang is missing.
 */

// ── Supported languages (allowlist) ─────────────────────────────────────────
export const SUPPORTED_LANGUAGES = {
  en: "English",
  id: "Bahasa Indonesia",
  ja: "日本語",
} as const;

export type LanguageCode = keyof typeof SUPPORTED_LANGUAGES;

export const LANGUAGE_OPTIONS: { code: LanguageCode; flag: string; label: string }[] = [
  { code: "en", flag: "🇺🇸", label: "English" },
  { code: "id", flag: "🇮🇩", label: "Bahasa Indonesia" },
  { code: "ja", flag: "🇯🇵", label: "日本語" },
];

export function isSupportedLanguage(value: unknown): value is LanguageCode {
  return typeof value === "string" && value in SUPPORTED_LANGUAGES;
}

/** The launch languages are all LTR. Kept as a compatibility helper for the provider. */
export function isRTL(_lang: LanguageCode): boolean {
  return false;
}

/** Read persisted language from localStorage, validated against the allowlist. */
export function getStoredLanguage(): LanguageCode {
  try {
    const stored = localStorage.getItem("mindful_language");
    if (stored && isSupportedLanguage(stored)) return stored;
    // Migrate retired or malformed persisted settings so future mounts are stable.
    if (stored !== null) {
      localStorage.setItem("mindful_language", "en");
      return "en";
    }

    const browserLanguage = typeof navigator !== "undefined"
      ? navigator.language.toLowerCase().split("-")[0]
      : "";
    if (isSupportedLanguage(browserLanguage)) {
      localStorage.setItem("mindful_language", browserLanguage);
      return browserLanguage;
    }
  } catch {
    // SSR or storage denied
  }
  return "en";
}

